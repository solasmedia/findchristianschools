-- Enrichment & Activities: tutor / class / sports / camp / youth-group /
-- music & arts / homeschool listings + listing reports.
-- Verification is admin-reviewed (no external check APIs): a listing only
-- shows a badge when verificationStatus = 'approved'.
CREATE TABLE IF NOT EXISTS `enrichment_listings` (
  `id` int NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `name` varchar(255) NOT NULL,
  `slug` varchar(255) NOT NULL UNIQUE,
  `category` enum('tutor','classes','sports','camps','youth_groups','music_arts','homeschool_coop') NOT NULL,
  `subcategory` varchar(128) NULL,
  `listerType` enum('individual','business','organization') NOT NULL DEFAULT 'business',
  `description` text NULL,
  `address` varchar(512) NULL,
  `city` varchar(128) NOT NULL,
  `state` varchar(64) NOT NULL,
  `stateCode` varchar(2) NOT NULL,
  `zip` varchar(10) NOT NULL,
  `latitude` decimal(10,7) NULL,
  `longitude` decimal(10,7) NULL,
  `phone` varchar(20) NULL,
  `email` varchar(320) NULL,
  `website` varchar(512) NULL,
  `contactName` varchar(255) NULL,
  `contactEmail` varchar(320) NULL,
  `contactPhone` varchar(20) NULL,
  `agesOrGrades` varchar(128) NULL,
  `denomination` varchar(128) NULL,
  `logoUrl` varchar(512) NULL,
  `coverImageUrl` varchar(512) NULL,
  `statementOfFaith` text NULL,
  `sofAttested` boolean NOT NULL DEFAULT false,
  `sofAttestedAt` timestamp NULL,
  `certifiedAccurate` boolean DEFAULT false,
  `listingType` enum('free','premium') NOT NULL DEFAULT 'free',
  `isPremium` boolean NOT NULL DEFAULT false,
  `premiumExpiresAt` timestamp NULL,
  `featured` boolean NOT NULL DEFAULT false,
  `stripeCustomerId` varchar(255) NULL,
  `stripeSubscriptionId` varchar(255) NULL,
  `stripePaymentIntentId` varchar(255) NULL,
  `promoCode` varchar(50) NULL,
  `promoDiscountPercent` int NULL,
  `ownerId` int NULL,
  `verificationStatus` enum('none','pending','approved','rejected') NOT NULL DEFAULT 'none',
  `verificationType` enum('none','documents','id_background') NOT NULL DEFAULT 'none',
  `ein` varchar(32) NULL,
  `legalName` varchar(255) NULL,
  `idAttested` boolean DEFAULT false,
  `backgroundCheckAttested` boolean DEFAULT false,
  `backgroundCheckDate` date NULL,
  `reference1Name` varchar(255) NULL,
  `reference1Contact` varchar(255) NULL,
  `reference2Name` varchar(255) NULL,
  `reference2Contact` varchar(255) NULL,
  `verifiedAt` timestamp NULL,
  `verifiedBy` varchar(255) NULL,
  `verificationNotes` text NULL,
  `listingStatus` enum('pending','active','removed','suspended','community_submitted') NOT NULL DEFAULT 'community_submitted',
  `isApproved` boolean NOT NULL DEFAULT false,
  `internalNotes` text NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_enrichment_category` (`category`),
  INDEX `idx_enrichment_state` (`stateCode`),
  INDEX `idx_enrichment_zip` (`zip`),
  INDEX `idx_enrichment_public` (`isApproved`, `listingStatus`),
  INDEX `idx_enrichment_verification` (`verificationStatus`)
);

CREATE TABLE IF NOT EXISTS `enrichment_reports` (
  `id` int NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `listingId` int NOT NULL,
  `listingName` varchar(255) NULL,
  `reason` enum('fraudulent','incorrect_info','inappropriate','closed','safety_concern','other') NOT NULL,
  `details` text NULL,
  `reporterName` varchar(255) NULL,
  `reporterEmail` varchar(320) NULL,
  `status` enum('pending','reviewed','actioned','dismissed') NOT NULL DEFAULT 'pending',
  `adminNotes` text NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_enrichment_reports_listing` (`listingId`),
  INDEX `idx_enrichment_reports_status` (`status`)
);
